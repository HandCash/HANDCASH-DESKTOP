import type * as sdk from '../../sdk'
import { StorageIdb } from '../StorageIdb'

const provenTxReqStatusesSafeForInputRestore = new Set<sdk.ProvenTxReqStatus>(['invalid', 'doubleSpend'])

/**
 * 1. set transactions to 'failed' if not already failed and provenTxReq with matching txid has status of 'invalid'.
 */
async function failTransactionsForInvalidReqs(storage: StorageIdb, r: { log: string }): Promise<void> {
  const invalidTxids: string[] = []
  await storage.filterProvenTxReqs({ partial: { status: 'invalid' } }, txReq => {
    invalidTxids.push(txReq.txid)
  })
  for (const txid of invalidTxids) {
    const txs = await storage.findTransactions({ partial: { txid } })
    for (const tx of txs) {
      if (tx.status !== 'failed') {
        r.log += `transaction ${tx.transactionId} updated to status of 'failed' was ${tx.status}\n`
        await storage.updateTransactionStatus('failed', tx.transactionId)
      }
    }
  }
}

/**
 * Partitions failed transactions into all failed ids and the subset that is safe for input restore
 * (terminal failure: no blocking ProvenTxReq, i.e. all reqs are 'invalid'/'doubleSpend').
 */
async function collectFailedTransactionIds(
  storage: StorageIdb
): Promise<{ failedTransactionIds: Set<number>; safeFailedTransactionIds: Set<number>; keyOf: Map<number, string> }> {
  const failedTxs = await storage.findTransactions({ partial: { status: 'failed' }, noRawTx: true })
  const failedTransactionIds = new Set<number>()
  const safeFailedTransactionIds = new Set<number>()
  const keyOf = new Map<number, string>()
  const settled = settledFailures(storage)
  for (const tx of failedTxs) {
    failedTransactionIds.add(tx.transactionId)
    const key = `${tx.transactionId}:${new Date(tx.updated_at).getTime()}`
    keyOf.set(tx.transactionId, key)
    if (settled.has(key)) continue
    let hasBlockingReq = false
    if (tx.txid != null && tx.txid !== '') {
      const reqs = await storage.findProvenTxReqs({ partial: { txid: tx.txid } })
      hasBlockingReq = reqs.some(req => !provenTxReqStatusesSafeForInputRestore.has(req.status))
    }
    if (!hasBlockingReq) safeFailedTransactionIds.add(tx.transactionId)
  }
  return { failedTransactionIds, safeFailedTransactionIds, keyOf }
}

/**
 * Failed transactions (id and last update) whose outputs a review already
 * brought in line this session. Their outputs cannot drift back without the
 * row changing, so each later review skips them: a phone with a long failed
 * history re-walked every one of them each 15 minutes under the storage lock.
 */
const settledByStorage = new WeakMap<StorageIdb, Set<string>>()
function settledFailures(storage: StorageIdb): Set<string> {
  let set = settledByStorage.get(storage)
  if (set == null) settledByStorage.set(storage, (set = new Set()))
  return set
}

/**
 * Looks for unpropagated state:
 *
 * 1. set transactions to 'failed' if not already failed and provenTxReq with matching txid has status of 'invalid'.
 * 2. sets outputs to spendable true, spentBy undefined if spentBy is a terminal failed transaction.
 * 3. sets outputs generated by terminal failed transactions to spendable false, spentBy undefined.
 *
 * @param storage
 * @param args
 * @returns
 */
export async function reviewStatusIdb(
  storage: StorageIdb,
  args: { agedLimit: Date; trx?: sdk.TrxToken }
): Promise<{ log: string }> {
  const r: { log: string } = { log: '' }

  await failTransactionsForInvalidReqs(storage, r)

  const { failedTransactionIds, safeFailedTransactionIds, keyOf } = await collectFailedTransactionIds(storage)
  const settled = settledFailures(storage)

  // Only outputs spent by or generated by a terminal failed transaction can
  // change, so read those through the spentBy / transactionId indexes. A scan
  // of every output (scripts and remittance included) held the storage lock
  // for 44s on a phone with ~2.5k items, with a send waiting behind it.
  for (const failedId of safeFailedTransactionIds) {
    const spent = await storage.findOutputs({ partial: { spentBy: failedId }, noScript: true, trx: args.trx })
    for (const output of spent) {
      // An output generated by any failed tx (even one still reconcilable from an active req) is
      // not a valid input to restore, matching the SQL `source.status = 'failed'` guard.
      if (failedTransactionIds.has(output.transactionId)) continue
      await storage.updateOutput(output.outputId, { spendable: true, spentBy: undefined }, args.trx)
      r.log += `output ${output.outputId} updated to spendable because spentBy is failed\n`
    }

    const generated = await storage.findOutputs({
      partial: { transactionId: failedId },
      noScript: true,
      trx: args.trx
    })
    for (const output of generated) {
      if (!output.spendable && output.spentBy == null) continue
      await storage.updateOutput(output.outputId, { spendable: false, spentBy: undefined }, args.trx)
      r.log += `output ${output.outputId} updated to not spendable because transaction is failed\n`
    }
    const key = keyOf.get(failedId)
    if (key != null) settled.add(key)
  }

  return r
}
