import 'fake-indexeddb/auto'
import { describe, expect, it, vi } from 'vitest'
import { PrivateKey } from '@bsv/sdk'
import { StorageIdb } from '@handcash/wallet-engine'

const OWNER = PrivateKey.fromRandom().toPublicKey().toString()
const OLD = new Date(Date.now() - 60 * 60_000)
const stamp = { created_at: OLD, updated_at: OLD }

const randomTxid = () =>
  Array.from(crypto.getRandomValues(new Uint8Array(32)), (b) => b.toString(16).padStart(2, '0')).join('')

async function openStorage(): Promise<{ storage: StorageIdb; userId: number }> {
  const storage = new StorageIdb({
    chain: 'main',
    feeModel: { model: 'sat/kb', value: 1 },
    commissionSatoshis: 0,
  } as ConstructorParameters<typeof StorageIdb>[0])
  storage.dbName = `review-status-${crypto.randomUUID()}`
  await storage.migrate(storage.dbName, PrivateKey.fromRandom().toPublicKey().toString())
  await storage.makeAvailable()
  const { user } = await storage.findOrInsertUser(OWNER)
  return { storage, userId: user.userId }
}

describe('reviewStatus on IndexedDB', () => {
  it('repairs outputs of terminal failed transactions without scanning every output', async () => {
    const { storage, userId } = await openStorage()
    const tx = async (status: 'completed' | 'failed') => {
      const txid = randomTxid()
      const transactionId = await storage.insertTransaction({
        ...stamp, transactionId: 0, userId, status, reference: `ref-${txid.slice(0, 8)}`,
        isOutgoing: true, satoshis: -1, description: 'review', version: 1, lockTime: 0, txid,
      })
      return { txid, transactionId }
    }
    let vout = 0
    const output = async (
      owner: { txid: string; transactionId: number },
      row: { spendable: boolean; spentBy?: number },
    ) =>
      storage.insertOutput({
        ...stamp, outputId: 0, userId, transactionId: owner.transactionId, change: false,
        outputDescription: 'review', vout: vout++, satoshis: 1, providedBy: 'you', purpose: '',
        type: 'P2PKH', txid: owner.txid, lockingScript: [0x51], ...row,
      })
    const request = (txid: string, status: string) =>
      (storage as unknown as { insertProvenTxReq: (row: Record<string, unknown>) => Promise<number> })
        .insertProvenTxReq({
          ...stamp, provenTxReqId: 0, attempts: 1, txid, status, notified: false,
          history: '{}', notify: '{}', rawTx: [1, 2, 3],
        })

    const funding = await tx('completed')
    const terminal = await tx('failed')
    await request(terminal.txid, 'invalid')
    const pending = await tx('failed')
    await request(pending.txid, 'unmined')
    const otherFailed = await tx('failed')
    await request(otherFailed.txid, 'sending')

    const freed = await output(funding, { spendable: false, spentBy: terminal.transactionId })
    const heldByPending = await output(funding, { spendable: false, spentBy: pending.transactionId })
    const untouched = await output(funding, { spendable: true })
    const terminalChange = await output(terminal, { spendable: true })
    const pendingChange = await output(pending, { spendable: true })
    const failedSpentByTerminal = await output(otherFailed, { spendable: false, spentBy: terminal.transactionId })

    const findOutputs = vi.spyOn(storage, 'findOutputs')
    const { log } = await storage.reviewStatus({ agedLimit: new Date() })
    for (const [args] of findOutputs.mock.calls) {
      expect(Object.keys(args.partial), 'a full outputs scan').not.toHaveLength(0)
    }

    const row = async (outputId: number) => (await storage.findOutputs({ partial: { outputId } }))[0]!
    expect(await row(freed)).toMatchObject({ spendable: true })
    expect((await row(freed)).spentBy ?? undefined).toBeUndefined()
    expect(await row(heldByPending)).toMatchObject({ spendable: false, spentBy: pending.transactionId })
    expect(await row(untouched)).toMatchObject({ spendable: true })
    expect(await row(terminalChange)).toMatchObject({ spendable: false })
    expect(await row(pendingChange)).toMatchObject({ spendable: true })
    // Generated by a failed tx that is not terminal: never restored, never cleared.
    expect(await row(failedSpentByTerminal)).toMatchObject({ spendable: false, spentBy: terminal.transactionId })
    expect(log).toContain(`output ${freed} updated to spendable`)
    expect(log).toContain(`output ${terminalChange} updated to not spendable`)
  })

  it('walks a settled failed transaction once a session, and again only once its row changes', async () => {
    const { storage, userId } = await openStorage()
    const txid = randomTxid()
    const transactionId = await storage.insertTransaction({
      ...stamp, transactionId: 0, userId, status: 'failed', reference: `ref-${txid.slice(0, 8)}`,
      isOutgoing: true, satoshis: -1, description: 'review', version: 1, lockTime: 0, txid,
    })
    const walks = () => findOutputs.mock.calls.filter(([args]) => args.partial?.spentBy === transactionId).length
    const findOutputs = vi.spyOn(storage, 'findOutputs')

    await storage.reviewStatus({ agedLimit: new Date() })
    expect(walks()).toBe(1)
    await storage.reviewStatus({ agedLimit: new Date() })
    expect(walks()).toBe(1)

    await storage.updateTransaction(transactionId, { updated_at: new Date() } as never)
    await storage.reviewStatus({ agedLimit: new Date() })
    expect(walks()).toBe(2)
  })
})

describe('TaskReviewStatus', () => {
  it('checks UTXOs holding no storage lock, and one bad request defers only itself', async () => {
    const { TaskReviewStatus } = await import('../../packages/wallet-engine/src/monitor/tasks/TaskReviewStatus')
    let held = false
    const heldDuringCheck: boolean[] = []
    const reconciled: number[] = []
    const sp = {
      completedProvenTxReqsToReconcile: async () => [
        { req: { provenTxReqId: 1 }, outputs: [] },
        { req: { provenTxReqId: 2 }, outputs: [] },
      ],
      proofRecoveryVerdicts: async () => {
        heldDuringCheck.push(held)
        await new Promise((r) => setTimeout(r, 1))
        return new Map()
      },
      reconcileCompletedProvenTxReq: async (req: { provenTxReqId: number }) => {
        if (req.provenTxReqId === 1) throw new Error('Output 7 changed while preparing proof recovery.')
        reconciled.push(req.provenTxReqId)
        return `completed req ${req.provenTxReqId} transaction notifications reconciled\n`
      },
      reviewStatus: async () => ({ log: '' }),
    }
    const storage = {
      async runAsStorageProvider<T>(body: (active: typeof sp) => Promise<T>): Promise<T> {
        held = true
        try {
          return await body(sp)
        } finally {
          held = false
        }
      },
    }
    const task = new TaskReviewStatus({ storage } as never)
    const log = await task.runTask()
    expect(heldDuringCheck).toEqual([false, false])
    expect(reconciled).toEqual([2])
    expect(log).toContain('completed req 1 deferred: Output 7 changed')
    expect(log).toContain('completed req 2 transaction notifications reconciled')
  })
})
